// Detect OS/browser language manually, avoiding the LanguageDetector plugin
// which may throw in restricted webview environments
function detectLanguage() {
  if (savedLanguage) return savedLanguage;
  const nav = (navigator.language || navigator.languages?.[0] || 'en').toLowerCase();
  if (nav.startsWith('pt')) return 'pt-BR';
  return 'en';
}

i18n
  .use(initReactI18next)
  .init({
    resources: {
      'pt-BR': { translation: { ...pptxViewerEn, ...pptxViewerPtBR, ...ptBR } },
      pt: { translation: { ...pptxViewerEn, ...pptxViewerPtBR, ...ptBR } },
      en: { translation: { ...pptxViewerEn, ...en } },
    },
    lng: detectLanguage(),
    fallbackLng: 'en',
    initImmediate: false,
    parseMissingKeyHandler: (key, defaultValue) => {
      if (typeof defaultValue === 'string' && defaultValue) return defaultValue;
      if (typeof key === 'string' && key.startsWith('pptx.')) return keyToLabel(key);
      return key;
    },
    interpolation: {
      escapeValue: false,
    },
  });

export default i18n;
